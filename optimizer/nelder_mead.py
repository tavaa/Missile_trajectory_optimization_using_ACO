import numpy as np
import copy

class NelderMeadSimplex:
    """
    Implementation of the Nelder-Mead Simplex method for Local Search.
    Designed to be coupled with ContinuousACO data structures.
    
    This algorithm performs a direct search method (derivative-free) to fine-tune 
    the best solution found by the ACO. It operates by maintaining a simplex of 
    n+1 points in n-dimensional space and transforming it via reflection, 
    expansion, contraction, and shrinking operations.

    Reference: Figure 5 of the paper (Simplex Morphology).
    """

    def __init__(self, aco_instance, ls_config):
        """
        Initializes the Nelder-Mead optimizer with problem bounds and configuration.

        Args:
            aco_instance (ContinuousACO): Instance of the parent ACO algorithm 
                                          (used to inherit bounds and variable names).
            ls_config (dict): Dictionary containing local search configuration 
                              (max_calls, tolerance, initial_step).
        """
        # 1. Inherit geometric context from ACO
        self.min_bounds = aco_instance.min_bounds
        self.max_bounds = aco_instance.max_bounds
        self.var_names = aco_instance.var_names
        self.n_vars = aco_instance.n_vars
        
        # 2. Simplex Coefficients (Standard values)
        # These coefficients define how aggressive the simplex deformation is.
        self.alpha = 1.0  # Reflection coefficient
        self.gamma = 2.0  # Expansion coefficient
        self.rho = 0.5    # Contraction coefficient
        self.sigma = 0.5  # Shrink coefficient
        
        # 3. Budget and Step Configuration
        self.max_calls = ls_config['max_calls']      # Maximum function calls per execution
        self.tolerance = float(ls_config['tolerance']) # Convergence threshold
        self.step_ratio = ls_config['initial_step']  # Initial simplex size (% of variable range)

    def _eval_wrapper(self, vector, func):
        """
        Helper method to convert a numpy array into a dictionary required by 
        the fitness function.

        Args:
            vector (np.array): Design variable vector.
            func (callable): The objective function.

        Returns:
            float: The calculated fitness value.
        """
        params = dict(zip(self.var_names, vector))
        return func(params)

    def _clip(self, vector):
        """
        Enforces physical constraints by clipping the vector within the defined bounds.
        
        Args:
            vector (np.array): The vector to check.

        Returns:
            np.array: The clipped vector.
        """
        return np.clip(vector, self.min_bounds, self.max_bounds)

    def search(self, start_vector, fitness_function):
        """
        Executes the Local Search starting from the best point found by the ACO.
        
        Args:
            start_vector (np.array): The vector of the best parameters found so far (Best Ant).
            fitness_function (callable): The objective function to minimize.
            
        Returns:
            tuple: (best_vector, best_fitness) found during the local search.
        """
        
        # --- 1. Simplex Initialization ---
        # A simplex in N dimensions consists of N+1 vertices.
        # Vertex 0 is the start point (ACO Best).
        # Vertices 1..N are generated by perturbing each dimension.
        
        simplex = np.zeros((self.n_vars + 1, self.n_vars))
        fitness = np.zeros(self.n_vars + 1)
        
        # Vertex 0: Starting point
        simplex[0] = start_vector
        fitness[0] = self._eval_wrapper(start_vector, fitness_function)
        
        # Vertices 1..N: Perturbation
        # Step size is proportional to the variable range (bounds)
        deltas = (self.max_bounds - self.min_bounds) * self.step_ratio
        
        for i in range(self.n_vars):
            point = np.copy(start_vector)
            # Add delta, but subtract if it exceeds the upper bound
            if point[i] + deltas[i] > self.max_bounds[i]:
                point[i] -= deltas[i]
            else:
                point[i] += deltas[i]
            
            simplex[i+1] = self._clip(point)
            fitness[i+1] = self._eval_wrapper(simplex[i+1], fitness_function)

        # Initialize local call counter
        # Note: fitness_function tracks global calls separately; this controls the local loop limit.
        calls = self.n_vars + 1 
        
        # --- 2. Main Optimization Loop (The "Amoeba") ---
        while calls < self.max_calls:
            
            # A. Sorting (Best -> Worst)
            indices = np.argsort(fitness)
            simplex = simplex[indices]
            fitness = fitness[indices]
            
            best_idx, worst_idx = 0, -1
            second_worst_idx = -2
            
            # Convergence Check
            # Stop if the difference between worst and best fitness is negligible
            if abs(fitness[worst_idx] - fitness[best_idx]) < self.tolerance:
                break
                
            # B. Centroid Calculation
            # Geometric mean of all points except the worst one
            centroid = np.mean(simplex[:-1], axis=0)
            
            # C. Reflection
            # Reflect the worst point through the centroid
            xr = self._clip(centroid + self.alpha * (centroid - simplex[worst_idx]))
            fr = self._eval_wrapper(xr, fitness_function)
            calls += 1
            
            if fitness[best_idx] <= fr < fitness[second_worst_idx]:
                # Case 1: Standard Improvement
                # Reflected point is better than second worst, but not the best.
                simplex[worst_idx] = xr
                fitness[worst_idx] = fr
                continue

            # D. Expansion
            if fr < fitness[best_idx]:
                # Case 2: New Best Found
                # The direction is promising, expand the simplex further.
                xe = self._clip(centroid + self.gamma * (xr - centroid))
                fe = self._eval_wrapper(xe, fitness_function)
                calls += 1
                
                if fe < fr:
                    simplex[worst_idx] = xe
                    fitness[worst_idx] = fe
                else:
                    simplex[worst_idx] = xr
                    fitness[worst_idx] = fr
                continue
                
            # E. Contraction
            # Reflection was not effective (worse than second worst).
            
            # Outside Contraction
            if fitness[second_worst_idx] <= fr < fitness[worst_idx]:
                xc = self._clip(centroid + self.rho * (xr - centroid))
                fc = self._eval_wrapper(xc, fitness_function)
                calls += 1
                
                if fc <= fr:
                    simplex[worst_idx] = xc
                    fitness[worst_idx] = fc
                    continue
                    
            # Inside Contraction (if reflection is worse than original worst point)
            if fr >= fitness[worst_idx]:
                xc = self._clip(centroid + self.rho * (simplex[worst_idx] - centroid))
                fc = self._eval_wrapper(xc, fitness_function)
                calls += 1
                
                if fc < fitness[worst_idx]:
                    simplex[worst_idx] = xc
                    fitness[worst_idx] = fc
                    continue

            # F. Shrink (Multi-Contraction)
            # If no improvement is found, shrink the entire simplex towards the best point.
            for i in range(1, len(simplex)):
                simplex[i] = self._clip(simplex[best_idx] + self.sigma * (simplex[i] - simplex[best_idx]))
                fitness[i] = self._eval_wrapper(simplex[i], fitness_function)
                calls += 1
        
        # End of budget or convergence reached
        # Re-sort one last time to return the absolute best
        indices = np.argsort(fitness)
        return simplex[indices[0]], fitness[indices[0]]